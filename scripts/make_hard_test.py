def pair(cat, pid, fusha, aranjiya, note=""):
    ROWS.append({"id": f"{pid}-f", "pair_id": pid, "category": cat, "label": "fusha", "text": fusha, "note": note})
    ROWS.append({"id": f"{pid}-a", "pair_id": pid, "category": cat, "label": "aranjiya", "text": aranjiya, "note": note})


def single(cat, sid, label, text, note=""):
    ROWS.append({"id": sid, "pair_id": None, "category": cat, "label": label, "text": text, "note": note})


